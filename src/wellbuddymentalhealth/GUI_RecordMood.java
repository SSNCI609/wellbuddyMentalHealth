    // take spaces off the start and end
    private String stripSpaces(String text) {
        // remove spaces at the start
        while (text.length() > 0) {
            // substring(0, 1) is the first character
            String first = text.substring(0, 1);
            if (first.equals(" ")
                    || first.equals("\n")
                    || first.equals("\t")
                    || first.equals("\r")) {
                // drop the first character
                text = text.substring(1);
            } else {
                // no more spaces at the start
                break;
            }
        }
        // remove spaces at the end
        while (text.length() > 0) {
            // last character in the string
            String last = text.substring(
                text.length() - 1);
            if (last.equals(" ")
                    || last.equals("\n")
                    || last.equals("\t")
                    || last.equals("\r")) {
                // drop the last character
                text = text.substring(
                    0, text.length() - 1);
            } else {
                // no more spaces at the end
                break;
            }
        }
        // return the cleaned text
        return text;
    }

